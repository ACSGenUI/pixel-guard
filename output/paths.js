import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const PACKAGE_ROOT = path.dirname(fileURLToPath(import.meta.url));
/**
 * Workspace root for generated artifacts (page comparisons, playwright reports).
 * Set via MCP config env PROJECT_ROOT — same pattern as ui-audit remote setup.
 */
export const PROJECT_ROOT = path.resolve(process.env.PROJECT_ROOT?.trim() || process.cwd());
/** @deprecated Use PROJECT_ROOT */
export const REPO_ROOT = PROJECT_ROOT;
/** @deprecated Reports live directly under PROJECT_ROOT/<reportId>/ */
export const PAGE_COMPARE_REPORTS_DIR = PROJECT_ROOT;
/** Report folder: PROJECT_ROOT/<reportId>/ */
export function getReportDir(reportId) {
    return path.join(PROJECT_ROOT, reportId);
}
/** URL path prefix for serving a report over HTTP. */
export function getPageComparisonReportBasePath(reportId) {
    return `/reports/${reportId}`;
}
/** Playwright HTML report directory (generated by visual tests in the project). */
export const PLAYWRIGHT_REPORT_DIR = path.resolve(process.env.PLAYWRIGHT_REPORT_DIR ?? path.join(PROJECT_ROOT, "playwright-report"));
export const PLAYWRIGHT_REPORT_INDEX = path.join(PLAYWRIGHT_REPORT_DIR, "index.html");
/** Compiled UI bundle directory (output/ when built, package root when running via tsx). */
export const DIST_DIR = fs.existsSync(path.join(PACKAGE_ROOT, "pixel-guard.html"))
    ? PACKAGE_ROOT
    : fs.existsSync(path.join(PACKAGE_ROOT, "output", "pixel-guard.html"))
        ? path.join(PACKAGE_ROOT, "output")
        : PACKAGE_ROOT;
export function getPageComparisonReportUrl(reportId, reportDir) {
    const isStdio = !process.argv.includes("--http");
    const origin = process.env.PIXEL_GUARD_ORIGIN?.replace(/\/$/, "") ||
        (isStdio ? "" : `http://localhost:${process.env.PORT ?? "3003"}`);
    if (origin) {
        return `${origin}${getPageComparisonReportBasePath(reportId)}/manifest.json`;
    }
    return path.join(reportDir, "manifest.json");
}
